package com.mycompany.atv3;

public class Atv3 {

    public static void main(String[] args) {
        int i, r=0, num=5;
        System.out.println("Tabuada do n°: "+num);
        for (i=0; i<=10; i++) {
            r=num*i;
            System.out.println(num+"X"+i+"="+r);
            System.exit(0);
        }
    }
}
